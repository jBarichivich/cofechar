test_that("graphical functions take one panel each and keep the caller's grid", {
  f <- system.file("extdata", "CL-MIR.rwl", package = "cofechar")
  invisible(capture.output(rwl <- dpl_read_dec(f)))
  cof <- dpl_cof(rwl[, 1:10], parts = integer(0), verbose = FALSE)
  pdf(NULL); on.exit(dev.off(), add = TRUE)
  par(mfrow = c(2, 3))
  mar0 <- par("mar")
  plot_cof_barplot(cof);                       expect_equal(par("mfg")[1:2], c(1L, 1L))
  plot(1:3);                                   expect_equal(par("mfg")[1:2], c(1L, 2L))
  plot_cof_coverage(rwl);                      expect_equal(par("mfg")[1:2], c(1L, 3L))
  plot_cof_coverage(rwl, depth = FALSE);       expect_equal(par("mfg")[1:2], c(2L, 1L))
  plot_cof_rings(rwl[, 1:5]);                  expect_equal(par("mfg")[1:2], c(2L, 2L))
  plot_cof_rings(rwl[, 1:5], xaxis = "length"); expect_equal(par("mfg")[1:2], c(2L, 3L))
  expect_equal(par("mfrow"), c(2L, 3L))
  expect_equal(par("mar"), mar0)
})
